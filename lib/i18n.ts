const dict: Record<Lang, Strings> = { en, te, ta, hi };

export function getStrings(lang: string | null | undefined): Strings {
  return dict[(lang as Lang) || "en"] || en;
}

export function getStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  const l = window.localStorage.getItem("gw_lang");
  return (["en", "te", "ta", "hi"].includes(l || "") ? l : "en") as Lang;
}

export function storeLang(lang: Lang) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem("gw_lang", lang);
  }
}
